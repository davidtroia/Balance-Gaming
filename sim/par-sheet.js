// Writes docs/par-sheet.md from the config and a simulator JSON report.
// Usage: node sim/simulate.js 50000000 2026 --json=report.json
//        node sim/par-sheet.js report.json

import fs from 'node:fs';
import * as C from '../engine/config.js';
import { buildReels } from '../engine/engine.js';

const report = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const reels = buildReels(C);
const pct = (x, d = 2) => (x * 100).toFixed(d) + '%';
const oneIn = (x) => (x ? `1 in ${Math.round(x).toLocaleString()}` : 'not observed');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const symbols = Object.keys(C.SYMBOLS);
const countRows = (set) => symbols.map((s) => [C.SYMBOLS[s].name, ...set.map((r) => r[s] || 0)]);

const md = `# Mardi Gras Mayhem — Par Sheet

*Generated by \`sim/par-sheet.js\` from ${report.spins.toLocaleString()} simulated rounds (seed ${report.seed}). Lab certification will verify these figures independently.*

## Summary

${table(['Measure', 'Value'], [
  ['Return to player', `${pct(report.rtp, 3)} (±${pct(report.rtp95, 3)} at 95% confidence)`],
  ['Hit frequency (any win)', `${pct(report.hitFrequency)} (1 in ${(1 / report.hitFrequency).toFixed(2)})`],
  ['Free Spins Parade', oneIn(report.freeSpinsOneIn)],
  ['Doubloon Hold & Win', oneIn(report.holdAndWinOneIn)],
  ['Grand jackpot (full board)', oneIn(report.grandOneIn)],
  ['Max win (5,000x) reached', oneIn(report.cappedOneIn)],
  ['Standard deviation per round', report.standardDeviation.toFixed(2)],
  ['Largest win observed', `${report.maxWinSeen.toFixed(2)}x`],
])}

## RTP by component

${table(['Component', 'RTP'], Object.entries(report.breakdown).map(([k, v]) => [k, pct(v, 3)]))}

## Win distribution (multiples of total bet)

${table(['Round win', 'Share of rounds'], report.distribution.map((d) => [d.range, pct(d.share, 4)]))}

## Game rules

- 5 reels x 4 rows, 1,024 ways, wins pay left to right on adjacent reels, 3+ of a kind.
- Wild (reels 2–4) substitutes for all pay symbols.
- **Climbing Wilds:** 1 in ${C.CLIMBING_WILDS.chanceIn} base rounds, 1/2/3 of reels 2–4 turn fully wild (weights ${Object.values(C.CLIMBING_WILDS.reelCountWeights).join('/')}).
- **Free Spins Parade:** 3/4/5 scatters pay ${Object.values(C.SCATTER_PAY).join('/')}x and award ${Object.values(C.FREE_SPINS_AWARD).join('/')} free spins on separate reels. Each wild landed adds +1x to a persistent multiplier (max ${C.FS_MULT_CAP}x). 3+ scatters retrigger +${C.FREE_SPINS_RETRIGGER} spins.
- **Doubloon Hold & Win:** ${C.HOLD_AND_WIN.trigger}+ coins in a base round lock and award ${C.HOLD_AND_WIN.respins} respins. Each empty cell spins a single-cell strip of ${C.HOLD_AND_WIN.cellStrip.COIN} coin : ${C.HOLD_AND_WIN.cellStrip.BLANK} blanks. A new coin resets respins. Filling all 20 cells adds the Grand (${C.HOLD_AND_WIN.grand.value}x).
- Total round win is capped at ${C.MAX_WIN.toLocaleString()}x the bet.

## Paytable (x total bet, per way)

${table(['Symbol', '3', '4', '5'], Object.entries(C.PAYTABLE).map(([s, p]) => [C.SYMBOLS[s].name, p[3], p[4], p[5]]))}

## Coin values (x total bet)

${table(['Value', 'Weight', 'Label'], C.COIN_VALUES.map((c) => [c.value, c.weight, c.jackpot || '']))}

## Reel strip symbol counts

Base game (strip lengths ${reels.base.map((s) => s.length).join(', ')}):

${table(['Symbol', 'Reel 1', 'Reel 2', 'Reel 3', 'Reel 4', 'Reel 5'], countRows(C.BASE_REELS))}

Free spins (strip lengths ${reels.free.map((s) => s.length).join(', ')}):

${table(['Symbol', 'Reel 1', 'Reel 2', 'Reel 3', 'Reel 4', 'Reel 5'], countRows(C.FREE_REELS))}

Stack heights: ${Object.entries(C.STACK).map(([s, n]) => `${C.SYMBOLS[s].name} ${n}`).join(', ')}; all other symbols single.

## Full base-game strips (stop order)

${reels.base.map((s, i) => `Reel ${i + 1}: \`${s.join(' ')}\``).join('\n\n')}
`;

fs.mkdirSync(new URL('../docs/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../docs/par-sheet.md', import.meta.url), md);
console.log('Wrote docs/par-sheet.md');
